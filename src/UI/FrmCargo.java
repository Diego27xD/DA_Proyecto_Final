    private void btnGrabarCargoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGrabarCargoActionPerformed
 
String descripcion = txtDescCargo.getText().trim();

if (descripcion.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Ingrese la descripcion del cargo");
    txtDescCargo.requestFocus();
    return;
}

if (!txtIdCargo.getText().trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Esta seleccionando un cargo existente. "
            + "Limpie los campos para registrar uno nuevo.");
    return;
}

CargoDAO dao = new CargoDAO();

boolean resultado = dao.grabarCargo(descripcion);

if (resultado) {

    javax.swing.JOptionPane.showMessageDialog(
            this, "Cargo registrado correctamente");

    txtIdCargo.setText("");
    txtDescCargo.setText("");
    tblCargos.clearSelection();

    cargarCargos();
    txtDescCargo.requestFocus();

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this, "Error al registrar el cargo");
}
    }//GEN-LAST:event_btnGrabarCargoActionPerformed

