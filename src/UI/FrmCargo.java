    private void btnModificarCargoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarCargoActionPerformed

String textoId = txtIdCargo.getText().trim();
String descripcion = txtDescCargo.getText().trim();

if (textoId.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Seleccione un cargo de la tabla");
    return;
}

if (descripcion.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Ingrese la descripcion del cargo");
    return;
}

int idCargo;

try {
    idCargo = Integer.parseInt(textoId);
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "El ID del cargo no es valido");
    return;
}

int opcion = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "¿Desea modificar este cargo?",
        "Confirmar modificacion",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (opcion == javax.swing.JOptionPane.YES_OPTION) {

    CargoDAO dao = new CargoDAO();

    boolean resultado =
            dao.modificarCargo(idCargo, descripcion);

    if (resultado) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Cargo modificado correctamente");

        txtIdCargo.setText("");
        txtDescCargo.setText("");
        txtBuscarCargo.setText("");

        cargarCargos();
        tblCargos.clearSelection();

        txtDescCargo.requestFocus();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this, "No se pudo modificar el cargo");
    }
}
    }//GEN-LAST:event_btnModificarCargoActionPerformed

