public void cargarCargos() {

    CargoDAO dao = new CargoDAO();

    Vector<Cargo> lista = dao.listaCargos("");

    DefaultTableModel modelo =
        (DefaultTableModel) tblCargos.getModel();

    modelo.setRowCount(0);

    for (Cargo cargo : lista) {

        Object[] fila = {
            cargo.getIdCargo(),
            cargo.getDescArea()
        };

        modelo.addRow(fila);
    }
}

