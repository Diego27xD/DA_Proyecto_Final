    private void btnGenerarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarReporteActionPerformed
        int cantidadRegistrosRetornados = 100;
        String tipoEmpresa = "";
        String textoCantidad = this.txtCantidadResultado.getText().trim();
        
        if (!textoCantidad.isEmpty()) {
            try {
                cantidadRegistrosRetornados = Integer.parseInt(textoCantidad);

                if (cantidadRegistrosRetornados <= 0) {
                    javax.swing.JOptionPane.showMessageDialog(
                        this, "La cantidad debe ser mayor que cero."
                    );
                    return;
                }
            } catch (NumberFormatException ex) {
                javax.swing.JOptionPane.showMessageDialog(
                    this, "Ingrese una cantidad entera válida."
                );
                return;
            }
        }
        tipoEmpresa = this.cbxTipoEmpresa.getSelectedItem().toString();
        if(tipoEmpresa == "Todos"){
            tipoEmpresa = "";
        };
        
        HashMap map = new HashMap();
        map.put("parTipoEmpresa", tipoEmpresa);
        map.put("cantidadResultado", cantidadRegistrosRetornados);
        
        try{
            String ruta = "src/REPORTES/reporteEmpresasParametro.jasper";
            DbBean db = new DbBean();
            db.connectRep(ruta, map, true);
        }catch(SQLException ex){
            ex.printStackTrace();
        }catch(JRException ex){
            ex.printStackTrace();
        }

        
    }//GEN-LAST:event_btnGenerarReporteActionPerformed


