public void cargarGeneros() {

    GeneroDAO dao = new GeneroDAO();

    Vector<Genero> lista = dao.listaGeneros("");

    DefaultTableModel modelo =
            (DefaultTableModel) tblGeneros.getModel();

    modelo.setRowCount(0);

    for (Genero genero : lista) {

        Object[] fila = {
            genero.getIdGenero(),
            genero.getDescrip()
        };

        modelo.addRow(fila);
    }
}

