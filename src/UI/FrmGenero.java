    private void btnModificarGeneroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarGeneroActionPerformed
 
String textoId = txtIdGenero.getText().trim();
String descripcion = txtDescGenero.getText().trim();

if (textoId.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Seleccione un genero de la tabla");
    return;
}

if (descripcion.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Ingrese la descripcion del genero");
    return;
}

int idGenero;

try {
    idGenero = Integer.parseInt(textoId);
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "El ID del genero no es valido");
    return;
}

if (idGenero == 1 || idGenero == 2) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "No modifique Masculino ni Femenino durante la prueba");
    return;
}

int opcion = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "¿Desea modificar este genero?",
        "Confirmar modificacion",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (opcion == javax.swing.JOptionPane.YES_OPTION) {

    GeneroDAO dao = new GeneroDAO();

    boolean resultado =
            dao.modificarGenero(idGenero, descripcion);

    if (resultado) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Genero modificado correctamente");

        txtIdGenero.setText("");
        txtDescGenero.setText("");
        txtBuscarGenero.setText("");

        cargarGeneros();
        tblGeneros.clearSelection();

        txtDescGenero.requestFocus();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this, "No se pudo modificar el genero");
    }
}
    }//GEN-LAST:event_btnModificarGeneroActionPerformed

    private void btnEliminarGeneroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarGeneroActionPerformed

String textoId = txtIdGenero.getText().trim();

if (textoId.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Seleccione un genero de la tabla");
    return;
}

int idGenero;

try {
    idGenero = Integer.parseInt(textoId);
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "El ID del genero no es valido");
    return;
}

if (idGenero == 1 || idGenero == 2) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "No se pueden eliminar los generos originales durante la practica");
    return;
}

int opcion = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "¿Esta seguro de eliminar este genero?",
        "Confirmar eliminacion",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (opcion == javax.swing.JOptionPane.YES_OPTION) {

    GeneroDAO dao = new GeneroDAO();

    boolean resultado = dao.eliminarGenero(idGenero);

    if (resultado) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Genero eliminado correctamente");

        txtIdGenero.setText("");
        txtDescGenero.setText("");
        txtBuscarGenero.setText("");

        tblGeneros.clearSelection();
        cargarGeneros();

        txtDescGenero.requestFocus();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "No se pudo eliminar el genero. "
                + "Puede estar relacionado con otros registros.");
    }
}
    }//GEN-LAST:event_btnEliminarGeneroActionPerformed

