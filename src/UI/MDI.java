    private void sMnuRequisitoRolActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_sMnuRequisitoRolActionPerformed
        java.util.Vector<BEAN.Rol> roles = new DAO.RolDAO().listaRoles(false, "");
        if(roles.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "No hay roles registrados");
            return;
        }
        String[] nombres = new String[roles.size()];
        for(int i = 0; i < roles.size(); i++){
            nombres[i] = roles.get(i).getIdRol() + " - " + roles.get(i).getDescRol();
        }
        Object sel = javax.swing.JOptionPane.showInputDialog(this, "Seleccione el rol", "Requisito de Rol",
                javax.swing.JOptionPane.QUESTION_MESSAGE, null, nombres, nombres[0]);
        if(sel != null){
            int pos = java.util.Arrays.asList(nombres).indexOf(sel.toString());
            FrmRequisitoRol dlg = new FrmRequisitoRol(this, true, roles.get(pos).getIdRol(), roles.get(pos).getDescRol());
            dlg.setLocationRelativeTo(this);
            dlg.setVisible(true);
        }
    }//GEN-LAST:event_sMnuRequisitoRolActionPerformed

